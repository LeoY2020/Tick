QString Tr::t(const QString& zh, const QString& en) {
    const int idx = supportedLangs().indexOf(s_lang);
    if (idx >= 0) {
        const QStringList& list = trTable().value(zh);
        if (!list.isEmpty() && idx < list.size()) {
            return list.at(idx);
        }
    }
    // 未命中的 key 或无匹配语言：回退旧逻辑（英文返回英译，其余返回中文）
    if (s_lang == QLatin1String("en")) return en;
    return zh;
}

